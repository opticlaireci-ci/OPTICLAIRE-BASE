// Date de création fixe (déterministe) pour ne pas altérer l'idempotence.
const seedDate = '2024-12-31T00:00:00.000Z';

function build(rows: Row[], month: string): ExtraContact[] {
  return rows.map(([client, telephone], i) => ({
    id: `seed_palm_${month}_${String(i + 1).padStart(3, '0')}`,
    client,
    telephone,
    month,
    createdAt: seedDate,
  }));
}

